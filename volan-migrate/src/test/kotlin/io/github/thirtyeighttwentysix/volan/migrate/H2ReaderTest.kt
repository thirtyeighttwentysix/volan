              time Time @default(dbgenerated("TIME '12:34:56.123456789'"))
              token Uuid @default(uuid())
              document Json @default("{}")
              bytes Bytes?
              strings String[] @default([])
              integers Int[] @default([])
              longs Long[] @default([])
              floats Float[] @default([])
              doubles Double[] @default([])
              decimals Decimal[] @default([])
              flags Boolean[] @default([])
              moments DateTime[] @default([])
              dates Date[] @default([])
              times Time[] @default([])
